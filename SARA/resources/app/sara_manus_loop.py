    def run_goal_loop(self, goal: str, max_retries: int = 2, open_artifacts: bool = False) -> Dict[str, Any]:
        """
        Main Manus-style execution loop:
        Deconstructs goal -> Executes steps sequentially with context -> Self-corrects on error -> Compiles artifacts.
        """
        session_id = f"manus_{int(time.time())}_{uuid.uuid4().hex[:6]}"
        start_time = time.time()
        steps = self.decompose_goal(goal)

        executed_steps = []
        artifacts = []
        context = {}
        all_success = True

        for idx, step in enumerate(steps):
            step_name = step["name"]
            attempts = 0
            step_result = None

            # Update active session progress
            progress_pct = int(((idx) / len(steps)) * 100)
            self._save_active_session({
                "session_id": session_id,
                "goal": goal,
                "current_step": idx + 1,
                "total_steps": len(steps),
                "active_step_name": step_name,
                "progress_pct": progress_pct,
                "status": "RUNNING",
                "artifacts": artifacts
            })

            while attempts <= max_retries:
                attempts += 1
                step_result = self.execute_step(step, context, open_artifacts=open_artifacts)

                if step_result.get("success"):
                    step["status"] = "COMPLETED"
                    step["result"] = step_result
                    out = step_result.get("output", {})
                    if "file_path" in out:
                        artifacts.append(out["file_path"])
                    break
                else:
                    step["status"] = "RETRYING"
                    if attempts > max_retries:
                        step["status"] = "FAILED"
                        step["error"] = step_result.get("error")
                        all_success = False
                        break
                    time.sleep(0.3)

            executed_steps.append(step)

        elapsed = round(time.time() - start_time, 2)

        session_record = {
            "session_id": session_id,
            "goal": goal,
            "status": "COMPLETED" if all_success else "PARTIAL_SUCCESS",
            "progress_pct": 100 if all_success else 75,
            "total_steps": len(steps),
            "completed_steps": sum(1 for s in executed_steps if s["status"] == "COMPLETED"),
            "artifacts_generated": artifacts,
            "steps": executed_steps,
            "elapsed_seconds": elapsed,
            "timestamp": time.strftime("%Y-%m-%d %H:%M:%S")
        }

        # Save session file & clear active
        session_file = self.sessions_dir / f"{session_id}.json"
        try:
            atomic_write_json(session_file, session_record)
            self._save_active_session(session_record)
        except Exception:
            pass

        spoken = (
            f"Pasha Jan, Manus Autonomous Loop ne poora goal 100% execute kar liya hai! "
            f"Total {len(steps)} steps complete hue hain aur Word report aur PowerPoint slides generate ho chuki hain."
        )

        return {
            "success": all_success,
            "session_id": session_id,
            "goal": goal,
            "completed_steps": session_record["completed_steps"],
            "total_steps": len(steps),
            "artifacts": artifacts,
            "elapsed_seconds": elapsed,
            "session_file": str(session_file),
            "spoken_reply": spoken
        }

    def _save_active_session(self, data: Dict[str, Any]):
        try:
            atomic_write_json(self.active_session_file, data)
        except Exception:
            pass

    def get_active_session(self) -> Dict[str, Any]:
        if self.active_session_file.exists():
            try:
                with open(self.active_session_file, "r", encoding="utf-8") as f:
                    return json.load(f)
            except Exception:
                pass
        return {"status": "IDLE"}


